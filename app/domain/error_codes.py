class DomainError(Exception):
    """An error that carries a stable machine code next to its message.

    The code is the class default unless the raise passes its own: one class can cover many
    conditions, and the code tells them apart.
    """

    code: str = ""

    def __init__(self, message: str = "", *, code: str | None = None):
        super().__init__(message)
        if code is not None:
            self.code = code


class Invalid(DomainError, ValueError):
    """A bad value in the request."""


class InvalidReference(Invalid):
    """An id in the request body names nothing in this workspace (422, never 404: 404 is the URL)."""

    def __init__(self, field: str):
        super().__init__(
            f"{field.replace('_', ' ')} does not exist in this workspace",
            code=f"invalid_{field}_id",
        )


class Forbidden(DomainError, PermissionError):
    """The caller may not do this."""


class Missing(DomainError, LookupError):
    """Something the caller named does not exist."""
