"""Write the reference docs from the code, so they cannot drift: api.md, mcp.md, schema.md, config.md.

Run: ./run.sh docs. A test fails when the committed files differ from what this writes.
"""

from pathlib import Path

from app.core.config import Settings
from app.db import models  # noqa: F401  (registers every table)
from app.db.base import Base
from app.integrations.mcp.core import _SPECS
from app.main import app

HERE = Path(__file__).parent
METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"]


def auth(dependant) -> str:
    """What the route demands, read from its dependencies."""
    for dep in dependant.dependencies:
        call = dep.call
        if call.__name__ == "service_only":
            return "service key only"
        if call.__qualname__.startswith("allow.") and call.__closure__:
            free = {
                n: c.cell_contents
                for n, c in zip(call.__code__.co_freevars, call.__closure__, strict=True)
            }
            scope, write = free.get("scope"), free.get("write_scope")
            if scope is None:
                return "service key only"
            return f"scope `{scope}`" + (f", writes `{write}`" if write else "")
        found = auth(dep)
        if found:
            return found
    return ""


def routes() -> dict[str, list[tuple]]:
    by_tag: dict[str, list[tuple]] = {}
    seen = set()
    for router in (r for r in app.routes if hasattr(r, "effective_route_contexts")):
        for ctx in router.effective_route_contexts():
            if not ctx.include_in_schema:
                continue
            for method in sorted(ctx.methods - {"HEAD", "OPTIONS"}, key=METHODS.index):
                key = (method, ctx.path)
                if key in seen:
                    continue
                seen.add(key)
                summary = (ctx.summary or ctx.name.replace("_", " ")).strip()
                by_tag.setdefault((ctx.tags or ["Other"])[0], []).append(
                    (ctx.path, METHODS.index(method), method, summary, auth(ctx.dependant))
                )
    return by_tag


def api_md() -> str:
    spec = app.openapi()["paths"]
    out = [
        "# REST API",
        "",
        "Generated by `./run.sh docs`. `{ws}` is the workspace id. Auth: the service key",
        "(`X-Data-API-Key`, optionally `X-Acting-Member-Id`) passes every route; a bearer token",
        "must hold the scope shown. Request and response bodies: `GET /openapi.json`.",
    ]
    for tag, rows in sorted(routes().items()):
        out += ["", f"## {tag}", "", "| Route | What | Auth |", "| --- | --- | --- |"]
        for path, _, method, summary, needs in sorted(rows):
            doc = spec.get(path, {}).get(method.lower(), {}).get("summary") or summary
            short = path.replace("/workspaces/{workspace_id}", "/workspaces/{ws}")
            out.append(f"| `{method} {short}` | {doc} | {needs or 'any valid caller'} |")
    return "\n".join(out) + "\n"


def mcp_md() -> str:
    out = [
        "# MCP tools",
        "",
        "Generated by `./run.sh docs`. Endpoint `POST /mcp`, `Authorization: Bearer <token>`.",
        "The workspace comes from the token; no tool takes a workspace argument.",
        "",
        "| Tool | Reads only | What |",
        "| --- | --- | --- |",
    ]
    for _, spec in sorted(_SPECS, key=lambda s: s[1]["name"]):
        ann = spec.get("annotations")
        ro = "yes" if ann is not None and ann.readOnlyHint else "no"
        out.append(f"| `{spec['name']}` | {ro} | {' '.join(spec['description'].split())} |")
    return "\n".join(out) + "\n"


def schema_md() -> str:
    out = [
        "# Database schema",
        "",
        "Generated by `./run.sh docs` from the SQLAlchemy models. `*` marks a primary key,",
        "`?` a nullable column, `->` a foreign key.",
    ]
    for name, table in sorted(Base.metadata.tables.items()):
        refs: dict[str, str] = {}
        for fk in table.foreign_key_constraints:
            cols = [c.name for c in fk.columns]
            own = [c for c in cols if c != "workspace_id"] or cols
            if len(own) == 1:  # composite (workspace_id, x_id) keys are one reference to x
                refs[own[0]] = fk.referred_table.name
        cols = [
            f"{c.name}{'*' if c.primary_key else ''}{'?' if c.nullable else ''}"
            + (f"->{refs[c.name]}" if c.name in refs else "")
            for c in table.columns
        ]
        out.append(f"- **{name}**: {', '.join(cols)}")
    return "\n".join(out) + "\n"


def config_md() -> str:
    out = [
        "# Configuration",
        "",
        "Generated by `./run.sh docs`. Environment variables (or `.env`) with their defaults.",
        "Required ones have no default.",
        "",
        "| Variable | Default |",
        "| --- | --- |",
    ]
    for name, field in Settings.model_fields.items():
        default = "required" if field.is_required() else f"`{field.default!r}`"
        out.append(f"| `{name}` | {default} |")
    return "\n".join(out) + "\n"


FILES = {"api.md": api_md, "mcp.md": mcp_md, "schema.md": schema_md, "config.md": config_md}

if __name__ == "__main__":
    for name, make in FILES.items():
        (HERE / name).write_text(make())
        print("wrote", HERE / name)
